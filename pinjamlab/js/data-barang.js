document.addEventListener('DOMContentLoaded', () => {
  const list = document.getElementById('katalog-items-list');
  if (!list) return;

  window.dataBarangInventaris.forEach((barang) => {
    const card = document.createElement('div');
    card.className = 'card catalog-card';
    card.dataset.category = barang.kategori;
    card.dataset.itemNo = String(barang.nomor);

    const thumbnail = document.createElement('div');
    thumbnail.className = 'item-thumb inventory-thumb';
    thumbnail.setAttribute('aria-hidden', 'true');
    thumbnail.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"><path d="m3 7 9-4 9 4-9 4-9-4Z"/><path d="M3 7v10l9 4 9-4V7"/><path d="M12 11v10"/></svg>';

    const info = document.createElement('div');
    info.className = 'item-info';

    const meta = document.createElement('span');
    meta.className = 'meta';
    meta.textContent = `No. ${barang.nomor} · ${barang.kategori === 'alat' ? 'Alat' : 'Bahan'}`;

    const name = document.createElement('span');
    name.className = 'name';
    name.textContent = barang.nama;

    const specification = document.createElement('span');
    specification.className = 'spec';
    specification.textContent = barang.spesifikasi;

    const row = document.createElement('div');
    row.className = 'card-row-between';

    const volume = document.createElement('span');
    volume.className = 'volume';
    volume.textContent = barang.volume === 'Buah'
      ? 'Volume: Buah · jumlah tidak dicantumkan'
      : `Volume: ${barang.volume}`;

    const addButton = document.createElement('button');
    addButton.type = 'button';
    addButton.className = 'add-btn';
    addButton.dataset.addItem = '';
    addButton.setAttribute('aria-label', `Tambah ${barang.nama}`);
    addButton.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><line x1="12" y1="5" x2="12" y2="19"/><line x1="5" y1="12" x2="19" y2="12"/></svg>';

    row.append(volume, addButton);
    info.append(meta, name, specification, row);
    card.append(thumbnail, info);
    list.appendChild(card);
  });

  const itemCount = document.getElementById('katalog-item-count');
  if (itemCount) itemCount.textContent = `${window.dataBarangInventaris.length} barang`;
});
